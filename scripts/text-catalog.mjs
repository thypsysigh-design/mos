import ExcelJS from 'exceljs';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const workbookPath = path.join(root, 'content/game-texts.xlsx');
const placeholders = text => [...new Set([...text.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(m => m[1]))].sort();
function cellText(cell, location) {
  const value = cell.value;
  if (value === null || value === undefined) return '';
  if (typeof value === 'string' || typeof value === 'number') return String(value);
  if (value.richText) return value.richText.map(part => part.text).join('');
  throw new Error(`${location}: formulas and unsupported cell types are not allowed`);
}
export async function readCatalog(file = workbookPath) {
  const book = new ExcelJS.Workbook(); await book.xlsx.readFile(file);
  const sheet = book.getWorksheet('Texts');
  if (!sheet) throw new Error('Missing Texts sheet');
  const headers = sheet.getRow(1).values.slice(1).map(v => String(v ?? ''));
  if (new Set(headers).size !== headers.length) throw new Error('Duplicate column headings');
  for (const header of ['ID', '분류', '위치', 'ko', '메모']) if (!headers.includes(header)) throw new Error(`Missing column: ${header}`);
  const languages = headers.filter(header => /^[a-z]{2}(?:-[A-Z]{2})?$/.test(header));
  const catalogs = Object.fromEntries(languages.map(language => [language, {}]));
  const seen = new Set();
  sheet.eachRow((row, number) => {
    if (number === 1) return;
    const get = header => cellText(row.getCell(headers.indexOf(header) + 1), `Row ${number}, ${header}`);
    const id = get('ID');
    if (!id && row.values.slice(1).every(v => v === null || v === undefined || v === '')) return;
    if (!/^[a-z][a-z0-9_.]*$/.test(id)) throw new Error(`Row ${number}: invalid ID ${id}`);
    if (seen.has(id)) throw new Error(`Duplicate ID: ${id}`);
    seen.add(id);
    const ko = get('ko');
    if (!ko.trim()) throw new Error(`${id}: Korean source must not be empty`);
    const required = placeholders(ko);
    for (const language of languages) {
      const value = get(language);
      if (!value.trim()) continue;
      if (JSON.stringify(placeholders(value)) !== JSON.stringify(required)) throw new Error(`${id} (${language}): placeholders must match ko: ${required.join(', ')}`);
      catalogs[language][id] = value;
    }
  });
  const manifest = JSON.parse(await fs.readFile(path.join(root, 'content/text-manifest.json'), 'utf8'));
  for (const entry of manifest) {
    if (!seen.has(entry.id)) throw new Error(`Required ID missing: ${entry.id}`);
    const actual = placeholders(catalogs.ko[entry.id]);
    const required = [...entry.notes.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(m => m[1]).sort();
    if (JSON.stringify(actual) !== JSON.stringify(required)) throw new Error(`${entry.id}: source placeholders changed; preserve ${entry.notes}`);
  }
  return catalogs;
}
export function generatedFiles(catalogs) {
  const languages = Object.keys(catalogs);
  const files = Object.fromEntries(languages.map(language => [`src/localization/${language}.json`, JSON.stringify(catalogs[language], null, 2) + '\n']));
  files['src/localization/catalogs.ts'] = '// Generated by npm run texts:import. Edit content/game-texts.xlsx instead.\n' + languages.map((language, i) => `import lang${i} from './${language}.json';`).join('\n') + '\nexport const catalogs = { ' + languages.map((language, i) => `${JSON.stringify(language)}: lang${i}`).join(', ') + ' };\n';
  return files;
}
